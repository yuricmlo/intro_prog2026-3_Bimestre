nomes = ["Maria","João","José","Rosa","Carlos","Alex","Joana","Renata"]
print(nomes[:4])
print(nomes[4:])
print(nomes[2:7])
print(nomes[::-1]) # - Imprime ao contrário, se estiver sozinho, ele imprime o último item
print(nomes[1:3])
print(nomes[::2])
print(nomes[1::2])
print(nomes[3::-1])  # Quando queremos ao contrário a partir de um item que a gente define, o primeiro parâmetro será o final.
